def potion_colors(rid):
    l = LIQ[rid]
    return {'o': 'k1', 'g': 'gl2', 'G': 'gl3', 'w': 'white', 'c': 'w3', 'C': 'w5', 'm': 'cu2', 's': 'a5',
            '0': l[0], '1': l[1], '2': l[2], '3': l[3], '4': l[4]}


def potion_small(rid):
    c = Canvas(7, 10)
    c.sprite(SMALL[rid], potion_colors(rid))
    return c


def potion_icon(rid):
    c = Canvas(16, 16)
    c.sprite(ICON[rid], potion_colors(rid))
